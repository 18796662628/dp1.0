function build_semi_steer_simulink_model()
% Build a kinematic Simulink model for the two-module semi-steer chassis.

model_name = "semi_steer_kinematic_model";
model_dir = fileparts(mfilename("fullpath"));
model_file = fullfile(model_dir, model_name + ".slx");

if bdIsLoaded(model_name)
    close_system(model_name, 0);
end
if isfile(model_file)
    delete(model_file);
end

new_system(model_name);
load_system("simulink");

add_block("simulink/Sources/Clock", model_name + "/Time", ...
    "Position", [30 105 60 135]);
add_block("simulink/User-Defined Functions/MATLAB Function", ...
    model_name + "/Motion profile", "Position", [90 65 135 155]);
add_block("simulink/User-Defined Functions/MATLAB Function", ...
    model_name + "/Two steer kinematics", "Position", [205 75 350 145]);
add_block("simulink/Signal Routing/Demux", model_name + "/Steer split", ...
    "Outputs", "2", "Position", [390 65 395 115]);
add_block("simulink/Signal Routing/Demux", model_name + "/Drive split", ...
    "Outputs", "2", "Position", [390 145 395 195]);

add_block("simulink/Continuous/Transfer Fcn", ...
    model_name + "/Front left steer actuator", ...
    "Numerator", "1", "Denominator", "[0.08 1]", ...
    "Position", [450 55 560 85]);
add_block("simulink/Continuous/Transfer Fcn", ...
    model_name + "/Rear right steer actuator", ...
    "Numerator", "1", "Denominator", "[0.08 1]", ...
    "Position", [450 100 560 130]);
add_block("simulink/Signal Routing/Mux", model_name + "/Actual steer", ...
    "Inputs", "2", "Position", [605 63 610 127]);
add_block("simulink/Sinks/To Workspace", model_name + "/steering actual", ...
    "VariableName", "steering_actual", "SaveFormat", "Timeseries", ...
    "Position", [650 83 740 113]);

add_block("simulink/Continuous/Transfer Fcn", ...
    model_name + "/Front left drive actuator", ...
    "Numerator", "1", "Denominator", "[0.05 1]", ...
    "Position", [450 145 560 175]);
add_block("simulink/Continuous/Transfer Fcn", ...
    model_name + "/Rear right drive actuator", ...
    "Numerator", "1", "Denominator", "[0.05 1]", ...
    "Position", [450 190 560 220]);
add_block("simulink/Signal Routing/Mux", model_name + "/Actual drive", ...
    "Inputs", "2", "Position", [605 153 610 217]);
add_block("simulink/Sinks/To Workspace", model_name + "/drive actual", ...
    "VariableName", "drive_actual", "SaveFormat", "Timeseries", ...
    "Position", [650 173 740 203]);

add_block("simulink/Continuous/Integrator", model_name + "/Yaw", ...
    "InitialCondition", "0", "Position", [350 330 380 360]);
add_block("simulink/User-Defined Functions/MATLAB Function", ...
    model_name + "/Body to world", "Position", [190 285 335 350]);
add_block("simulink/Signal Routing/Demux", model_name + "/World velocity", ...
    "Outputs", "3", "Position", [350 260 355 320]);
add_block("simulink/Continuous/Integrator", model_name + "/X position", ...
    "InitialCondition", "0", "Position", [415 245 445 275]);
add_block("simulink/Continuous/Integrator", model_name + "/Y position", ...
    "InitialCondition", "0", "Position", [415 290 445 320]);
add_block("simulink/Signal Routing/Mux", model_name + "/Pose", ...
    "Inputs", "3", "Position", [495 250 500 355]);
add_block("simulink/Sinks/To Workspace", model_name + "/pose", ...
    "VariableName", "pose", "SaveFormat", "Timeseries", ...
    "Position", [550 285 625 315]);

set_matlab_function(model_name + "/Two steer kinematics", [ ...
    "function [steer_deg, drive_aps] = fcn(vx, vy, wz, fl_actual_deg, rr_actual_deg)" newline ...
    "% x points forward, y points left, wz is counterclockwise." newline ...
    "wheel_base = 0.344;" newline ...
    "track_width = 0.344;" newline ...
    "wheel_radius = 0.055;" newline ...
    "reduction = 15.76;" newline ...
    "positions = [wheel_base/2, track_width/2; -wheel_base/2, -track_width/2];" newline ...
    "steer_deg = zeros(2,1);" newline ...
    "drive_aps = zeros(2,1);" newline ...
    "actual_deg = [fl_actual_deg; rr_actual_deg];" newline ...
    "for i = 1:2" newline ...
    "    vix = vx - wz * positions(i,2);" newline ...
    "    viy = vy + wz * positions(i,1);" newline ...
    "    speed = sqrt(vix*vix + viy*viy);" newline ...
    "    if speed > 0.01" newline ...
    "        desired_deg = atan2(viy, vix) * 180 / pi;" newline ...
    "        error_deg = mod(desired_deg - actual_deg(i) + 180, 360) - 180;" newline ...
    "        speed_sign = 1;" newline ...
    "        if abs(error_deg) > 90" newline ...
    "            error_deg = error_deg - sign(error_deg) * 180;" newline ...
    "            speed_sign = -1;" newline ...
    "        end" newline ...
    "        steer_deg(i) = actual_deg(i) + error_deg;" newline ...
    "        drive_aps(i) = speed_sign * speed * reduction * 360 / (2*pi*wheel_radius);" newline ...
    "    end" newline ...
    "end" newline ...
    "end" ]);

set_matlab_function(model_name + "/Motion profile", [ ...
    "function [vx, vy, wz] = fcn(t)" newline ...
    "% Stop, forward, lateral, rotate, diagonal, then stop." newline ...
    "vx = 0; vy = 0; wz = 0;" newline ...
    "if t >= 2 && t < 4" newline ...
    "    vx = 0.60;" newline ...
    "elseif t >= 4 && t < 6" newline ...
    "    vy = 0.45;" newline ...
    "elseif t >= 6 && t < 8" newline ...
    "    wz = 0.80;" newline ...
    "elseif t >= 8 && t < 10" newline ...
    "    vx = 0.50; vy = 0.25; wz = 0.40;" newline ...
    "end" newline ...
    "end" ]);

set_matlab_function(model_name + "/Body to world", [ ...
    "function world_dot = fcn(vx, vy, wz, yaw)" newline ...
    "% Ideal body-velocity plant for the first kinematic model." newline ...
    "c = cos(yaw);" newline ...
    "s = sin(yaw);" newline ...
    "world_dot = [vx*c - vy*s; vx*s + vy*c; wz];" newline ...
    "end" ]);

set_param(model_name, "SimulationCommand", "update");

add_line(model_name, "Time/1", "Motion profile/1");
add_line(model_name, "Motion profile/1", "Two steer kinematics/1");
add_line(model_name, "Motion profile/2", "Two steer kinematics/2");
add_line(model_name, "Motion profile/3", "Two steer kinematics/3");
add_line(model_name, "Two steer kinematics/1", "Steer split/1");
add_line(model_name, "Two steer kinematics/2", "Drive split/1");
add_line(model_name, "Steer split/1", "Front left steer actuator/1");
add_line(model_name, "Steer split/2", "Rear right steer actuator/1");
add_line(model_name, "Front left steer actuator/1", "Actual steer/1");
add_line(model_name, "Rear right steer actuator/1", "Actual steer/2");
add_line(model_name, "Front left steer actuator/1", "Two steer kinematics/4");
add_line(model_name, "Rear right steer actuator/1", "Two steer kinematics/5");
add_line(model_name, "Actual steer/1", "steering actual/1");
add_line(model_name, "Drive split/1", "Front left drive actuator/1");
add_line(model_name, "Drive split/2", "Rear right drive actuator/1");
add_line(model_name, "Front left drive actuator/1", "Actual drive/1");
add_line(model_name, "Rear right drive actuator/1", "Actual drive/2");
add_line(model_name, "Actual drive/1", "drive actual/1");

add_line(model_name, "Motion profile/1", "Body to world/1");
add_line(model_name, "Motion profile/2", "Body to world/2");
add_line(model_name, "Motion profile/3", "Body to world/3");
add_line(model_name, "Yaw/1", "Body to world/4");
add_line(model_name, "Body to world/1", "World velocity/1");
add_line(model_name, "World velocity/1", "X position/1");
add_line(model_name, "World velocity/2", "Y position/1");
add_line(model_name, "World velocity/3", "Yaw/1");
add_line(model_name, "X position/1", "Pose/1");
add_line(model_name, "Y position/1", "Pose/2");
add_line(model_name, "Yaw/1", "Pose/3");
add_line(model_name, "Pose/1", "pose/1");

set_param(model_name, "StopTime", "12", "Solver", "ode4", "FixedStep", "0.01");
save_system(model_name, model_file);
open_system(model_name);
end

function set_matlab_function(block_path, script)
root = sfroot;
chart = root.find("-isa", "Stateflow.EMChart", "Path", block_path);
chart.Script = char(script);
end
